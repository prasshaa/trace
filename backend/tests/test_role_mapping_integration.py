def test_database_alias_rows_equal_the_data_foundation_source(conn):
    repo = PostgresAliasRepository(conn)
    db_rows = repo.alias_rows()
    csv_rows, _, csv_roles = csv_index(additions=True)
    by_id = lambda rows: sorted(rows, key=lambda r: r.alias_id)      # noqa: E731
    assert by_id(db_rows) == by_id(csv_rows)      # includes alias_normalized as generated by the database
    assert repo.role_rows() == csv_roles
    assert conn.info.transaction_status == psycopg.pq.TransactionStatus.IDLE and not conn.read_only


def test_repository_refuses_a_connection_with_an_open_transaction(conn):
    with pytest.raises(RuntimeError):
        with conn.transaction():
            PostgresAliasRepository(conn).alias_rows()


def test_fixture_agreement_from_the_database(conn):
    repo = PostgresAliasRepository(conn)
    idx, roles = AliasIndex(repo.alias_rows()), repo.role_rows()
    profiles = [json.loads(l) for l in PROFILES.read_text(encoding="utf-8").splitlines() if l.strip()]
    rows = compare_fixtures(profiles, idx, roles)
    s = summarize(rows, idx)
    assert (s["profiles"], s["employments"]) == (41, 106)
    for r in rows:
        if r.match.outcome == "automatic":
            assert all(not o.role_id.startswith("ROLE-UNKNOWN") for o in r.match.options)
            assert r.match.mapping_status == "auto_high_confidence" and r.match.mapping_basis == "alias_match"
        else:
            assert r.match.proposed_role_id is None and r.match.mapping_confidence is None
    assert match_title("Product Owner", idx).outcome == "context_required"


# --------------------------------------------------------------------------- normalisation contract parity (Python == PostgreSQL)
from app.services.role_mapping import WHITESPACE, is_product_owner_title, normalize_title  # noqa: E402

PARITY_EXTRA = [0xFEFF, 0x180E, 0x200B, 0x200C, 0x200D, 0x2060, 0x212A, 0x2126, 0xFF21, 0xFF41, 0x1D400, 0x1F600, 0xE0020, 0x10FFFD]


def _parity_strings():
    chars = [chr(c) for c in range(1, 0x3100) if not 0xD800 <= c <= 0xDFFF] + [chr(c) for c in PARITY_EXTRA]
    out = []
    for ch in chars:
        out += [f"{ch}Product{ch}{ch}Owner{ch}", f"A{ch}b", ch, f" {ch} "]
    out += ["", " ", "\t\n", "".join(WHITESPACE), "Product" + "".join(WHITESPACE) + "Manager", "MiXeD CaSe Z", "Director – Product"]
    return out


def test_python_and_postgres_normalise_every_tested_character_identically(conn):
    titles = _parity_strings()
    with conn.transaction():
        db = conn.execute("select trace_util.normalize_title(t), trace_util.is_product_owner_title(t) from unnest(%s::text[]) with ordinality u(t, i) order by i",
                          (titles,)).fetchall()
    mismatches = [(t, n_db, normalize_title(t)) for t, (n_db, _) in zip(titles, db) if n_db != normalize_title(t)]
    assert not mismatches, mismatches[:5]
    po = [(t, p_db) for t, (_, p_db) in zip(titles, db) if p_db != is_product_owner_title(t)]
    assert not po, po[:5]
    assert len(titles) > 49000


def test_postgres_matches_the_python_product_owner_cases(conn):
    titles = ["Product Owner (Payments)", "Product Owner - Growth", "Senior Product Owner", "Product Ownership Lead", "Product-Owner",
              "Lead\u00a0Product\u3000Owner", "Product\u200bOwner", None]
    with conn.transaction():
        db = [r[0] for r in conn.execute("select trace_util.is_product_owner_title(t) from unnest(%s::text[]) with ordinality u(t, i) order by i",
                                         (titles,)).fetchall()]
    assert db == [is_product_owner_title(t) for t in titles] == [True, True, True, False, False, True, False, False]


def test_alias_rows_that_disagree_with_the_contract_are_refused(conn):
    with pytest.raises(psycopg.errors.CheckViolation):
        with conn.transaction():
            conn.execute("insert into public.trace_role_aliases (alias_id, alias, role_id, default_confidence) "
                         "values ('ALS-9950', E'\\tTab Led Title', 'PM-PM', 0.9)")
    with conn.transaction():
        assert conn.execute("select count(*) from public.trace_role_aliases where alias_normalized is distinct from trace_util.normalize_title(alias)").fetchone()[0] == 0
