"""Data shapes for deterministic title-to-role matching (M5, task 1).

Nothing here is written to the database. A ``TitleMatch`` is a *proposal* derived only from
``public.trace_role_aliases``; storing it, and the candidate's own role decision, are later tasks.
"""
from decimal import Decimal
from typing import Literal, Optional, Tuple

from pydantic import BaseModel, ConfigDict

MatchOutcome = Literal["automatic", "context_required", "unresolved"]
ProposedMappingStatus = Literal["auto_high_confidence", "needs_review", "unresolved"]
# How a role was chosen. The matcher only ever produces 'alias_match'; a candidate's own choice will
# be recorded as a different basis ('candidate_selected') so the two stay distinguishable.
MappingBasis = Literal["alias_match"]


class _Frozen(BaseModel):
    model_config = ConfigDict(extra="forbid", frozen=True)


class AliasRow(_Frozen):
    """One row of public.trace_role_aliases, joined to its role in public.trace_role_taxonomy."""
    alias_id: str
    alias: str
    alias_normalized: str                 # generated by the database; checked against normalize_title
    role_id: str
    seniority_hint_code: Optional[str]
    context_required: bool
    default_confidence: Decimal
    mapping_rule: Optional[str]
    role_default_seniority_code: str
    role_is_resolved: bool
    role_active: bool


class RoleInfo(_Frozen):
    """One row of public.trace_role_taxonomy, as far as mapping needs it."""
    role_id: str
    default_seniority_code: str
    is_resolved: bool
    active: bool


class RoleOption(_Frozen):
    """A role an alias can map to. For a context-required title these are the candidate's options."""
    alias_id: str
    alias: str
    role_id: str
    seniority_hint_code: Optional[str]    # the seniority override the alias carries, if any
    effective_seniority_code: str         # the hint, else the role's default seniority (trace_model.py)
    default_confidence: Decimal
    mapping_rule: Optional[str]
    role_is_resolved: bool


class TitleMatch(_Frozen):
    """The matcher's proposal for one title.

    * ``automatic``: exactly one alias row matched, it is not context-required, and its role is resolved
      and active. ``proposed_role_id``/``proposed_seniority_code`` are set, the status is
      ``auto_high_confidence`` and the confidence is the alias's ``default_confidence``.
    * ``context_required``: the matched alias rows are context-required (always so when a title maps to
      several roles). Nothing is proposed; ``options`` lists the roles a decision may choose from. The
      status is ``needs_review`` and is never confirmed automatically.
    * ``unresolved``: no alias matched (or the title is empty). Nothing is proposed.

    ``original_title`` is the input exactly as given; ``lookup_title`` is its normalised form.
    A proposal never changes review status: a pending record stays a barrier in sequencing.
    """
    original_title: Optional[str]
    lookup_title: Optional[str]
    outcome: MatchOutcome
    reason: str
    matched_alias_ids: Tuple[str, ...] = ()
    options: Tuple[RoleOption, ...] = ()
    proposed_role_id: Optional[str] = None
    proposed_seniority_code: Optional[str] = None       # override to store (the alias hint), or None
    effective_seniority_code: Optional[str] = None      # proposed override, else the role default
    mapping_status: ProposedMappingStatus
    mapping_confidence: Optional[Decimal] = None
    mapping_basis: Optional[MappingBasis] = None
    mapping_rule: Optional[str] = None
