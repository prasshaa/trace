"""Generate the seed migration for an approved target-role knowledge pack from its JSON source of truth.

    python scripts/build_knowledge_pack.py            # (re)write the migration
    python scripts/build_knowledge_pack.py --check    # fail if the migration differs from the JSON

The JSON (knowledge_packs/<pack>.json) is the reviewed, approved content: sources with licence, attribution and
verification dates; canonical requirements with the transferability mapping; requirement-source evidence; and
employer-specific criteria. The migration only inserts that content. It is curated public reference material, never
user data, and never synthetic test data.
"""
import argparse
import json
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
PACKS = {"pm-v1": ("knowledge_packs/pm-v1.json", "supabase/migrations/20261116120000_trace_pm_knowledge_pack_v1.sql", "2.17.0"),
         "pm-v1.1": ("knowledge_packs/pm-v1.1.json", "supabase/migrations/20261116140000_trace_pm_knowledge_pack_v1_1.sql", "2.20.0"),
         "pm-v1.2": ("knowledge_packs/pm-v1.2.json", "supabase/migrations/20261116190000_trace_pm_knowledge_pack_v1_2.sql", "2.25.0")}


def lit(v):
    if v is None:
        return "null"
    if isinstance(v, bool):
        return "true" if v else "false"
    if isinstance(v, (int, float)):
        return str(v)
    if isinstance(v, (list, tuple)):
        return "array[" + ", ".join(lit(x) for x in v) + "]::text[]" if v else "'{}'::text[]"
    if isinstance(v, dict):
        return lit(json.dumps(v, ensure_ascii=False, sort_keys=True)) + "::jsonb"
    return "'" + str(v).replace("'", "''") + "'"


def render(pack_key: str) -> str:
    src_path, _, version = PACKS[pack_key]
    pack = json.loads((ROOT / src_path).read_text(encoding="utf-8"))
    p = lit(pack["key"])
    out = [f"-- Trace data foundation v{version}: the approved {pack['key']} knowledge pack ({pack['role_family']}), approved "
           f"{pack['approved_on']}.",
           f"-- GENERATED by scripts/build_knowledge_pack.py from {src_path}. Do not edit by hand; edit the JSON and regenerate.",
           f"-- {pack['curation_note']}",
           "-- Curated public reference content: no user data, no synthetic test data.", ""]
    inventory = pack.get("sources_from", pack["key"])           # a revision reuses an approved source inventory unchanged
    if "sources_from" in pack:
        out.append(f"-- Requirements revision of {pack['changes_from']}: sources, criteria and provenance stay those of the "
                   f"{inventory} inventory (not re-inserted).")
    out.append("-- ------------------------------------------------------------------ sources")
    for s in pack.get("sources", []):
        cols = {
            "source_key": f"{pack['key']}:{s['key']}", "knowledge_pack": pack["key"], "source_kind": s["kind"], "source_type": s["source_type"],
            "company_name": s["company_name"], "publisher": s["publisher"], "role_title": s["role_title"], "role_id": s.get("role_id"),
            "location": s.get("location"), "geography": s.get("geography"), "source_url": s["url"], "published_at": s.get("published_at"),
            "retrieved_at": s["retrieved_at"], "last_verified_at": s["last_verified_at"], "revalidate_by": s.get("revalidate_by"),
            "source_status": s["status"], "status_note": s.get("status_note"), "licence": s["licence"], "attribution": s["attribution"],
            "level_as_stated": s.get("level_as_stated"), "context_tags": s.get("context_tags", []),
            "entry_background_stance": s.get("entry_background_stance"), "accepted_backgrounds": s.get("accepted_backgrounds", []),
            "excluded_backgrounds": s.get("excluded_backgrounds", []), "entry_quote": s.get("entry_quote"), "entry_locator": s.get("entry_locator"),
        }
        out.append(f"insert into public.trace_target_role_sources ({', '.join(cols)})\nvalues ({', '.join(lit(v) for v in cols.values())});")
    out.append("")
    out.append("-- ------------------------------------------------------------------ employer-specific criteria (per source; never canonical)")
    for s in pack.get("sources", []):
        for c in s.get("employer_criteria", []):
            out.append(
                "insert into public.trace_target_role_requirements (target_role_source_id, requirement_type, requirement_text, "
                "min_years_experience, importance, extracted_by, user_visible_explanation)\n"
                f"select target_role_source_id, {lit(c['requirement_type'])}, {lit(c['text'])}, {lit(c.get('min_years_experience'))}, "
                f"{lit(c['importance'])}, 'reviewer', {lit('Stated by ' + s['company_name'] + ' in one posting; employer-specific, not a general requirement.')}\n"
                f"  from public.trace_target_role_sources where source_key = {lit(pack['key'] + ':' + s['key'])};")
    out.append("")
    out.append("-- ------------------------------------------------------------------ canonical requirements and transferability mapping")
    for r in pack["requirements"]:
        cols = {
            "knowledge_pack": pack["key"], "requirement_key": r["key"], "role_family": pack["role_family"], "applies_to_level": r["applies_to_level"],
            "requirement_class": r["requirement_class"], "title": r["title"], "description": r["description"],
            "level_notes": r.get("level_notes") or {}, "contexts": r["contexts"], "direct_areas": r["direct_areas"],
            "transferable_areas": r["transferable_areas"], "direct_skills": r["direct_skills"], "transferable_skills": r["transferable_skills"],
            "transferable_role_families": r["transferable_role_families"], "transfer_rationale": r.get("transfer_rationale"), "gap_basis": r["gap_basis"],
        }
        if "area_conditions" in r:
            cols["area_conditions"] = r["area_conditions"]
        if "decision_rights" in r:                                   # pm-v1.2 (D31)
            cols["decision_rights"] = r["decision_rights"]
        if "area_condition_fallback" in r:                           # pm-v1.2 (D35)
            cols["area_condition_fallback"] = r["area_condition_fallback"]
        out.append(f"insert into public.trace_capability_requirements ({', '.join(cols)})\nvalues ({', '.join(lit(v) for v in cols.values())});")
    out.append("")
    out.append("-- ------------------------------------------------------------------ requirement <-> source evidence")
    for r in pack["requirements"]:
        seen = set()
        for e in r["evidence"]:
            if e["source"] in seen:
                raise SystemExit(f"duplicate evidence {r['key']}/{e['source']}")
            seen.add(e["source"])
            out.append(
                "insert into public.trace_requirement_source_evidence (capability_requirement_id, target_role_source_id, stance, locator, note)\n"
                f"select r.capability_requirement_id, s.target_role_source_id, {lit(e['stance'])}, {lit(e.get('locator'))}, {lit(e.get('note'))}\n"
                f"  from public.trace_capability_requirements r, public.trace_target_role_sources s\n"
                f" where r.knowledge_pack = {p} and r.requirement_key = {lit(r['key'])} and s.source_key = {lit(inventory + ':' + e['source'])};")
    return "\n".join(out) + "\n"


def main(argv=None) -> int:
    ap = argparse.ArgumentParser(description=__doc__.splitlines()[0])
    ap.add_argument("--check", action="store_true")
    args = ap.parse_args(argv)
    stale = []
    for key, (_, target, _) in PACKS.items():
        text, path = render(key), ROOT / target
        if args.check:
            if not path.exists() or path.read_text(encoding="utf-8") != text:
                stale.append(target)
        else:
            path.write_text(text, encoding="utf-8")
    if stale:
        print("Out of date:", ", ".join(stale))
        return 1
    print("Knowledge-pack migrations are up to date." if args.check else "Wrote knowledge-pack migrations.")
    return 0


if __name__ == "__main__":
    sys.exit(main())
