"""Generate the seed migration for the Phase 4 transition-planning content from its reviewed JSON (D27, D28, D29).

    python scripts/build_transition_content.py            # (re)write the migration
    python scripts/build_transition_content.py --check    # fail if the migration differs from the JSON

Inputs (the source of truth):
  knowledge_packs/pm-bridges-v1.json      bridge-role catalogue and its two new sources (D27)
  knowledge_packs/pm-actions-v1.json      action-template library (D28)
  knowledge_packs/pm-eligibility-v1.json  structured employer criteria and background-to-family mappings (D29)

The migration inserts the catalogue, its sources and the templates, and sets the new structured columns on the
existing pm-v1 employer criteria and postings (each update must match exactly one row, or the migration fails).
Curated public reference content: no user data, no synthetic test data.
"""
import argparse
import json
import sys
from pathlib import Path

sys.path.insert(0, str(Path(__file__).resolve().parent))
from build_knowledge_pack import lit  # noqa: E402  (the same literal rendering as the approved packs)

ROOT = Path(__file__).resolve().parents[1]
MIGRATION = "supabase/migrations/20261116160000_trace_pm_transition_content_v1.sql"
VERSION = "2.22.0"
BRIDGES, ACTIONS, ELIGIBILITY = ("knowledge_packs/pm-bridges-v1.json", "knowledge_packs/pm-actions-v1.json",
                                 "knowledge_packs/pm-eligibility-v1.json")
WHERE = {"current_job", "internal_move", "external_project", "self_directed_study", "job_market"}


def load(path):
    return json.loads((ROOT / path).read_text(encoding="utf-8"))


def validate(bridges, actions, elig):
    """Static checks before anything is rendered (the database checks again)."""
    pm = load("knowledge_packs/pm-v1.json")
    reqs = {r["key"] for r in load("knowledge_packs/pm-v1.1.json")["requirements"]}
    sources = {f"pm-v1:{s['key']}" for s in pm["sources"]} | {f"{bridges['key']}:{s['key']}" for s in bridges["sources"]}
    for b in bridges["bridges"]:
        assert set(b["develops"]) | set(b["partly_develops"]) | set(b["entry_signal_requirements"]) <= reqs, b["bridge_role_id"]
        assert set(b["source_keys"]) <= sources and b["source_keys"], b["bridge_role_id"]
        assert b["bridge_role_id"] not in ("ROLE-PGM", "ROLE-PROJ", "ROLE-TPGM"), "D27: no program/project management bridge"
    keys = set()
    for t in actions["templates"]:
        assert t["key"] not in keys, t["key"]
        keys.add(t["key"])
        assert set(t["where"]) <= WHERE and t["where"], t["key"]
        assert set(t["basis_sources"]) <= sources, t["key"]
        assert (t["requirement_key"] is None) or t["requirement_key"] in reqs, t["key"]
    for r in sorted(reqs):
        assert f"build.{r}" in keys and f"demonstrate.{r}" in keys, f"templates missing for {r}"
    posting = {s["key"]: s for s in pm["sources"] if s["kind"] == "job_posting"}
    stated = {(s["key"], c["text"]) for s in posting.values() for c in s.get("employer_criteria", [])}
    covered = {(c["source"], c["text"]) for c in elig["criteria"]}
    assert covered == stated, f"every employer criterion is structured exactly once: {sorted(stated ^ covered)}"
    for key, m in elig["background_families"].items():
        s = posting[key]
        if "accepted" in m:
            assert sorted(m["accepted"]) == sorted(s["accepted_backgrounds"]), key
        if "excluded" in m:
            assert sorted(m["excluded"]) == sorted(s["excluded_backgrounds"]), key


def render() -> str:
    bridges, actions, elig = load(BRIDGES), load(ACTIONS), load(ELIGIBILITY)
    validate(bridges, actions, elig)
    out = [f"-- Trace data foundation v{VERSION}: Phase 4 transition-planning content (D27 {bridges['key']}, D28 {actions['key']}, "
           f"D29 {elig['key']}).",
           "-- GENERATED by scripts/build_transition_content.py from the reviewed JSON files. Do not edit by hand; edit the JSON",
           "-- and regenerate.",
           f"-- D27: {bridges['curation_note']}",
           f"-- D28: {actions['curation_note']}",
           f"-- D29: {elig['curation_note']}",
           "-- Curated public reference content: no user data, no synthetic test data.", "",
           "-- ------------------------------------------------------------------ D27 sources (role-level definitions of the bridge roles)"]
    for s in bridges["sources"]:
        cols = {
            "source_key": f"{bridges['key']}:{s['key']}", "knowledge_pack": bridges["key"], "source_kind": s["kind"], "source_type": s["source_type"],
            "company_name": s["company_name"], "publisher": s["publisher"], "role_title": s["role_title"], "role_id": s.get("role_id"),
            "location": s.get("location"), "geography": s.get("geography"), "source_url": s["url"], "published_at": s.get("published_at"),
            "retrieved_at": s["retrieved_at"], "last_verified_at": s["last_verified_at"], "revalidate_by": s.get("revalidate_by"),
            "source_status": s["status"], "status_note": s.get("status_note"), "licence": s["licence"], "attribution": s["attribution"],
            "level_as_stated": s.get("level_as_stated"), "context_tags": s.get("context_tags", []),
        }
        out.append(f"insert into public.trace_target_role_sources ({', '.join(cols)})\nvalues ({', '.join(lit(v) for v in cols.values())});")
    out += ["", "-- ------------------------------------------------------------------ D27 bridge roles"]
    for b in bridges["bridges"]:
        cols = {
            "catalogue_version": bridges["key"], "target_role_id": b["target_role_id"], "bridge_role_id": b["bridge_role_id"],
            "requirements_pack": bridges["requirements_pack"], "responsibilities": b["responsibilities"], "develops": b["develops"],
            "partly_develops": b["partly_develops"], "develops_note": b["develops_note"], "entry_basis": b["entry_basis"],
            "entry_requirements_stated": b["entry_requirements_stated"], "entry_signal_families": b["entry_signal_families"],
            "entry_signal_requirements": b["entry_signal_requirements"], "suitable_backgrounds": b["suitable_backgrounds"],
            "suitability_note": b["suitability_note"], "tradeoff_note": b["tradeoff_note"], "level_step": b["level_step"],
            "source_keys": b["source_keys"], "source_notes": b["source_notes"],
        }
        out.append(f"insert into public.trace_bridge_roles ({', '.join(cols)})\nvalues ({', '.join(lit(v) for v in cols.values())});")
    out += ["", "-- ------------------------------------------------------------------ D28 action templates"]
    for t in actions["templates"]:
        cols = {
            "template_version": actions["key"], "template_key": t["key"], "requirements_pack": actions["requirements_pack"], "stage": t["stage"],
            "kind": t["kind"], "requirement_key": t["requirement_key"], "objective": t["objective"], "action_text": t["action"],
            "deliverable": t["deliverable"], "where_options": t["where"], "basis_sources": t["basis_sources"],
        }
        out.append(f"insert into public.trace_action_templates ({', '.join(cols)})\nvalues ({', '.join(lit(v) for v in cols.values())});")
    out += ["", "-- ------------------------------------------------------------------ D29 structured employer criteria and background families",
            "-- Each update sets only the new columns of exactly one existing pm-v1 row (checked below)."]
    inv = elig["source_inventory"]
    for c in elig["criteria"]:
        rule = {**c["rule"], "note": c["note"]} if c.get("note") else c["rule"]      # the curated reading, kept with the rule
        out.append(
            "do $$\ndeclare n integer;\nbegin\n"
            f"  update public.trace_target_role_requirements r set criterion = {lit(rule)}, criteria_version = {lit(elig['key'])}\n"
            f"   from public.trace_target_role_sources s\n"
            f"   where s.target_role_source_id = r.target_role_source_id and s.source_key = {lit(inv + ':' + c['source'])}\n"
            f"     and r.requirement_text = {lit(c['text'])};\n"
            "  get diagnostics n = row_count;\n"
            f"  if n <> 1 then raise exception 'D29: expected one criterion for {c['source']}, found %', n; end if;\nend\n$$;")
    for key, m in sorted(elig["background_families"].items()):
        acc = sorted({f for fams in m.get("accepted", {}).values() for f in fams})
        exc = sorted({f for fams in m.get("excluded", {}).values() for f in fams})
        out.append(f"update public.trace_target_role_sources set accepted_role_families = {lit(acc)}, excluded_role_families = {lit(exc)}\n"
                   f" where source_key = {lit(inv + ':' + key)};")
    return "\n".join(out) + "\n"


MIGRATION_V2 = "supabase/migrations/20261116200000_trace_pm_transition_content_v2.sql"
VERSION_V2 = "2.26.0"
BRIDGES_V2, ACTIONS_V2, ELIGIBILITY_V2 = ("knowledge_packs/pm-bridges-v2.json", "knowledge_packs/pm-actions-v2.json",
                                          "knowledge_packs/pm-eligibility-v2.json")
WHERE_V2 = WHERE | {"trace_profile"}
LABELS = {"learning_exercise", "personal_project_possible", "factual_accuracy", "trace_curated"}


def validate_v2(bridges, actions, elig):
    pm = load("knowledge_packs/pm-v1.json")
    reqs = {r["key"] for r in load("knowledge_packs/pm-v1.2.json")["requirements"]}
    sources = {f"pm-v1:{s['key']}" for s in pm["sources"]} | {f"pm-bridges-v1:{s['key']}" for s in load(BRIDGES)["sources"]}
    for b in bridges["bridges"]:
        rid = b["bridge_role_id"]
        assert set(b["develops"]) | set(b["partly_develops"]) | set(b["entry_signal_requirements"]) <= reqs, rid
        assert not set(b["develops"]) & set(b["partly_develops"]), rid
        assert set(b["partial_development"]) == set(b["partly_develops"]), rid
        assert all(v["develops"] and v["incomplete"] and v["seek"] for v in b["partial_development"].values()), rid
        assert set(b["source_keys"]) <= sources and b["source_keys"], rid
        assert b["entry_evidence"] in ("employer_stated", "source_stated_context", "target_plan", "hypothesis"), rid
        assert b["progression_evidence"] in ("source_stated", "hypothesis"), rid
        assert rid not in ("ROLE-PGM", "ROLE-PROJ", "ROLE-TPGM"), "D27"
    owner = next(b for b in bridges["bridges"] if b["bridge_role_id"] == "ROLE-OWNER")
    assert owner["may_be_primary"] is False and owner["entry_evidence"] == "hypothesis", "D34"
    for c in bridges["candidate_pool"]["roles"]:
        assert (c["mapping_confidence"] == "unmapped") == (c["trace_role_family"] is None), c["f1_role"]
    keys = set()
    for t in actions["templates"]:
        assert t["key"] not in keys, t["key"]
        keys.add(t["key"])
        assert set(t["where"]) <= WHERE_V2 and t["where"], t["key"]
        assert set(t["labels"]) <= LABELS, t["key"]
        assert set(t["basis_sources"]) <= sources, t["key"]
        if t["kind"] == "build":
            assert "learning_exercise" in t["labels"] and "learning exercise" in t["deliverable"], t["key"]
        if t["kind"] == "demonstrate" and "external_project" in t["where"]:
            assert "personal_project_possible" in t["labels"] and "personal project" in t["deliverable"], t["key"]
    for r in sorted(reqs):
        assert f"build.{r}" in keys and f"demonstrate.{r}" in keys, r
    posting = {s["key"]: s for s in pm["sources"] if s["kind"] == "job_posting"}
    stated = {(s["key"], c["text"]) for s in posting.values() for c in s.get("employer_criteria", [])}
    covered = [(c["source"], c["text"]) for c in elig["criteria"]]
    assert sorted(covered) == sorted(stated), "every employer criterion is structured exactly once"
    codes = {f["code"] for f in elig["education_fields"]} | {"category:" + f["category"] for f in elig["education_fields"]}
    aliases = [a for f in elig["education_fields"] for a in f["aliases"]]
    assert len(aliases) == len(set(aliases)), "an alias names one field"

    def walk(n):
        for x in (n.get("all") or n.get("any") or []):
            walk(x)
        if n.get("type") == "qualification":
            assert set(n["fields"]) <= codes, n
    for c in elig["criteria"]:
        walk(c["rule"])


def render_v2() -> str:
    bridges, actions, elig = load(BRIDGES_V2), load(ACTIONS_V2), load(ELIGIBILITY_V2)
    validate_v2(bridges, actions, elig)
    out = [f"-- Trace data foundation v{VERSION_V2}: Phase 4 remediation content (D31-D36): {bridges['key']}, {actions['key']}, {elig['key']}.",
           "-- GENERATED by scripts/build_transition_content.py from the reviewed JSON files. Do not edit by hand; edit the JSON",
           "-- and regenerate. Earlier versions (pm-bridges-v1, pm-actions-v1, pm-eligibility-v1) are kept unchanged for audit.",
           f"-- D32/D34: {bridges['curation_note']}",
           f"-- D33: {bridges['candidate_pool']['note']}",
           f"-- D28: {actions['curation_note']}",
           f"-- D36: {elig['curation_note']}",
           "-- Curated public reference content: no user data, no synthetic test data.", "",
           "-- ------------------------------------------------------------------ bridge roles v2"]
    for b in bridges["bridges"]:
        cols = {
            "catalogue_version": bridges["key"], "target_role_id": b["target_role_id"], "bridge_role_id": b["bridge_role_id"],
            "requirements_pack": bridges["requirements_pack"], "responsibilities": b["responsibilities"], "develops": b["develops"],
            "partly_develops": b["partly_develops"], "develops_note": b["develops_note"], "entry_basis": b["entry_basis"],
            "entry_requirements_stated": b["entry_requirements_stated"], "entry_signal_families": b["entry_signal_families"],
            "entry_signal_requirements": b["entry_signal_requirements"], "suitable_backgrounds": b["suitable_backgrounds"],
            "suitability_note": b["suitability_note"], "tradeoff_note": b["tradeoff_note"], "level_step": b["level_step"],
            "source_keys": b["source_keys"], "source_notes": b["source_notes"], "entry_evidence": b["entry_evidence"],
            "progression_evidence": b["progression_evidence"], "may_be_primary": b["may_be_primary"],
            "partial_development": b["partial_development"],
        }
        out.append(f"insert into public.trace_bridge_roles ({', '.join(cols)})\nvalues ({', '.join(lit(v) for v in cols.values())});")
    out += ["", "-- ------------------------------------------------------------------ D33 digital role candidate pool (not bridges)"]
    for c in bridges["candidate_pool"]["roles"]:
        cols = {"catalogue_version": bridges["key"], "f1_role": c["f1_role"], "trace_role_family": c["trace_role_family"],
                "mapping_confidence": c["mapping_confidence"], "summary": c["summary"], "shared_skills": c["shared_skills"],
                "develops": c["develops"], "suitable_backgrounds": c["suitable_backgrounds"], "source_key": bridges["candidate_pool"]["source"]}
        out.append(f"insert into public.trace_digital_role_candidates ({', '.join(cols)})\nvalues ({', '.join(lit(v) for v in cols.values())});")
    out += ["", "-- ------------------------------------------------------------------ action templates v2"]
    for t in actions["templates"]:
        cols = {
            "template_version": actions["key"], "template_key": t["key"], "requirements_pack": actions["requirements_pack"], "stage": t["stage"],
            "kind": t["kind"], "requirement_key": t["requirement_key"], "objective": t["objective"], "action_text": t["action"],
            "deliverable": t["deliverable"], "where_options": t["where"], "basis_sources": t["basis_sources"], "labels": t["labels"],
        }
        out.append(f"insert into public.trace_action_templates ({', '.join(cols)})\nvalues ({', '.join(lit(v) for v in cols.values())});")
    out += ["", "-- ------------------------------------------------------------------ education fields (whole-value aliases)"]
    for f in elig["education_fields"]:
        cols = {"field_code": f["code"], "label": f["label"], "category": f["category"], "aliases": f["aliases"]}
        out.append(f"insert into public.trace_education_fields ({', '.join(cols)})\nvalues ({', '.join(lit(v) for v in cols.values())});")
    out += ["", "-- ------------------------------------------------------------------ employer criterion rules v2 (one per stored criterion)"]
    inv = elig["source_inventory"]
    for c in elig["criteria"]:
        rule = {**c["rule"], "note": c["note"]} if c.get("note") else c["rule"]
        out.append(
            "do $$\ndeclare n integer;\nbegin\n"
            f"  insert into public.trace_employer_criterion_rules (rules_version, requirement_id, rule)\n"
            f"  select {lit(elig['key'])}, r.requirement_id, {lit(rule)}\n"
            f"    from public.trace_target_role_requirements r join public.trace_target_role_sources s using (target_role_source_id)\n"
            f"   where s.source_key = {lit(inv + ':' + c['source'])} and r.requirement_text = {lit(c['text'])};\n"
            "  get diagnostics n = row_count;\n"
            f"  if n <> 1 then raise exception 'D36: expected one criterion for {c['source']}, found %', n; end if;\nend\n$$;")
    return "\n".join(out) + "\n"


MIGRATION_V3 = "supabase/migrations/20261117100000_trace_pm_eligibility_v3.sql"
VERSION_V3 = "2.28.0"
ELIGIBILITY_V3 = "knowledge_packs/pm-eligibility-v3.json"


def render_v3() -> str:
    """pm-eligibility-v3 (Phase 4 closure): new rule rows only; v1 and v2 stay unchanged for audit."""
    bridges, actions, elig = load(BRIDGES_V2), load(ACTIONS_V2), load(ELIGIBILITY_V3)
    validate_v2(bridges, actions, elig)                       # the same coverage, field and alias checks as v2
    out = [f"-- Trace data foundation v{VERSION_V3}: employer criterion rules {elig['key']} (Phase 4 closure).",
           "-- GENERATED by scripts/build_transition_content.py from the reviewed JSON. Do not edit by hand.",
           f"-- {elig['approval_note']}", f"-- {elig['curation_note']}",
           "-- Curated public reference content: no user data, no synthetic test data.", "",
           "-- The two new leaf keys name existing taxonomy entries (checked here; the rule structure is checked by the table's trigger).",
           "do $$\nbegin\n"
           f"  if exists (select 1 from unnest({lit(sorted({r for c in elig['criteria'] for r in _keys(c['rule'], 'unconfirmed_roles')}))}) x\n"
           "              where not exists (select 1 from public.trace_role_taxonomy t where t.role_id = x)) then\n"
           "    raise exception 'unknown role in unconfirmed_roles';\n  end if;\n"
           f"  if exists (select 1 from unnest({lit(sorted({r for c in elig['criteria'] for r in _keys(c['rule'], 'before_families')}))}) x\n"
           "              where not exists (select 1 from public.trace_role_families f where f.role_family = x)) then\n"
           "    raise exception 'unknown family in before_families';\n  end if;\nend\n$$;", ""]
    inv = elig["source_inventory"]
    for c in elig["criteria"]:
        rule = {**c["rule"], "note": c["note"]} if c.get("note") else c["rule"]
        out.append(
            "do $$\ndeclare n integer;\nbegin\n"
            f"  insert into public.trace_employer_criterion_rules (rules_version, requirement_id, rule)\n"
            f"  select {lit(elig['key'])}, r.requirement_id, {lit(rule)}\n"
            f"    from public.trace_target_role_requirements r join public.trace_target_role_sources s using (target_role_source_id)\n"
            f"   where s.source_key = {lit(inv + ':' + c['source'])} and r.requirement_text = {lit(c['text'])};\n"
            "  get diagnostics n = row_count;\n"
            f"  if n <> 1 then raise exception 'v3: expected one criterion for {c['source']}, found %', n; end if;\nend\n$$;")
    return "\n".join(out) + "\n"


def _keys(node, key):
    found = list(node.get(key) or [])
    for x in (node.get("all") or node.get("any") or []):
        found += _keys(x, key)
    return found


OUTPUTS = ((MIGRATION, render), (MIGRATION_V2, render_v2), (MIGRATION_V3, render_v3))


def main() -> int:
    ap = argparse.ArgumentParser()
    ap.add_argument("--check", action="store_true")
    args = ap.parse_args()
    stale = []
    for target, fn in OUTPUTS:
        text, path = fn(), ROOT / target
        if args.check:
            if not path.exists() or path.read_text(encoding="utf-8") != text:
                stale.append(target)
        else:
            path.write_text(text, encoding="utf-8")
            print(f"Wrote {target}")
    if args.check:
        if stale:
            print("Out of date: " + ", ".join(stale) + "; run scripts/build_transition_content.py", file=sys.stderr)
            return 1
        print("Transition-content migrations are up to date.")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
