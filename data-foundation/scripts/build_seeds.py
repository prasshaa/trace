def source_row(s):
    return {"source_id": s["source_id"], "dataset_class": s["dataset_class"], "source_type": s["source_type"],
            "source_label": s["source_label"], "geographic_scope": s["geographic_scope"],
            "licence_or_permission": nullable(s["licence_or_permission"]),
            "permitted_uses": pipe_list(s["permitted_uses"]), "prohibited_uses": pipe_list(s["prohibited_uses"]),
            "provenance_note": nullable(s["provenance_note"])}


