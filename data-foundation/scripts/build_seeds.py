# --------------------------------------------------------------------------- SQL literals
def lit(v):
    if v is None:
        return "null"
    if isinstance(v, bool):
        return "true" if v else "false"
    if isinstance(v, (int, float)):
        return repr(v)
    if isinstance(v, (list, tuple)):
        if not v:
            return "'{}'::text[]"
        return "array[" + ", ".join(lit(x) for x in v) + "]::text[]"
    return "'" + str(v).replace("'", "''") + "'"


def upsert(table, cols, rows, conflict, update_cols=None):
    if not rows:
        return ""
    update_cols = [c for c in (update_cols or cols) if c not in conflict]
    values = ",\n".join("  (" + ", ".join(lit(r[c]) for c in cols) + ")" for r in rows)
    sets = ",\n  ".join(f"{c} = excluded.{c}" for c in update_cols)
    return (f"insert into {table} ({', '.join(cols)}) values\n{values}\n"
            f"on conflict ({', '.join(conflict)}) do update set\n  {sets};\n\n")


def pipe_list(v):
    return [x for x in (v or "").split("|") if x]


def nullable(v):
    return v if v not in ("", None) else None


def split_date(value, precision):
    y, m = tm.parse_partial_date(value, precision)
    return y, m


