def build_lookup_sql(lk):
    out = [GENERATED_BANNER.format(src="data/taxonomy, data/skills and data/config"),
           "-- Trace Data Foundation v2 · 11 · lookup data required in every environment.\n"
           "-- Upserts keyed on stable ids, so re-applying is harmless. Retire rows with active = false\n"
           "-- (roles) instead of deleting them; employment rows reference them.\n\n"]
    out.append(upsert("public.trace_seniority_levels", ["seniority_code", "label", "rank", "description"],
                      [{**r, "rank": int(r["rank"]) if r["rank"] else None} for r in lk["seniority"]], ["seniority_code"]))
    out.append(upsert("public.trace_role_families", ["role_family", "label", "is_product_management", "description"],
                      [{**r, "is_product_management": tm.as_bool(r["is_product_management"])} for r in lk["families"]], ["role_family"]))
    out.append(upsert("public.trace_role_taxonomy",
                      ["role_id", "role_family", "canonical_title", "default_seniority_code", "is_pm_target", "is_resolved", "active", "definition"],
                      [{**r, "is_pm_target": tm.as_bool(r["is_pm_target"]), "is_resolved": tm.as_bool(r["is_resolved"]),
                        "active": tm.as_bool(r["active"])} for r in lk["roles"]], ["role_id"]))
    out.append(upsert("public.trace_role_aliases",
                      ["alias_id", "alias", "role_id", "seniority_hint_code", "context_required", "default_confidence", "mapping_rule"],
                      [{**r, "seniority_hint_code": nullable(r["seniority_hint_code"]), "context_required": tm.as_bool(r["context_required"]),
                        "default_confidence": float(r["default_confidence"]), "mapping_rule": nullable(r["mapping_rule"])}
                       for r in lk["aliases"]], ["alias_id"]))
    out.append(upsert("public.trace_responsibility_areas", ["responsibility_area", "label", "is_pm_ownership_signal", "description"],
                      [{**r, "is_pm_ownership_signal": tm.as_bool(r["is_pm_ownership_signal"])} for r in lk["areas"]], ["responsibility_area"]))
    out.append(upsert("public.trace_skill_families", ["skill_family", "label", "description"],
                      [{**r, "description": nullable(r["description"])} for r in lk["skill_families"]], ["skill_family"]))
    out.append(upsert("public.trace_skills", ["skill_id", "canonical_skill", "skill_family", "description"],
                      [{**r, "description": nullable(r["description"])} for r in lk["skills"]], ["skill_id"]))
    out.append(upsert("public.trace_skill_aliases", ["alias", "skill_id"], lk["skill_aliases"], ["alias"]))
    out.append(upsert("trace_ref.analytics_settings", ["setting_key", "value_numeric", "unit", "description"],
                      [{**r, "value_numeric": float(r["value_numeric"])} for r in lk["settings"]], ["setting_key"]))
    out.append(upsert("trace_ref.data_sources", SOURCE_COLS,
                      [source_row(s) for s in lk["sources"] if s["seed_target"] == "lookup_migration"], ["source_id"]))
    return "".join(out).rstrip() + "\n"


