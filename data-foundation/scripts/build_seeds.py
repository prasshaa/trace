def flatten(profiles):
    t = {k: [] for k in ("profiles", "employers", "employments", "education", "career_breaks", "experience_evidence", "profile_skills")}
    for p in profiles:
        pid = p["profile_id"]
        ay, am = split_date(p.get("resume_as_of"), p["resume_as_of_precision"])
        t["profiles"].append({"profile_id": pid, "source_id": p["source_id"], "dataset_class": p["dataset_class"],
                              "country_code": p["country_code"], "region_group": p.get("region_group"),
                              "profile_summary": p.get("profile_summary"), "resume_as_of_year": ay, "resume_as_of_month": am,
                              "resume_as_of_precision": p["resume_as_of_precision"], "review_status": p["review_status"],
                              "scope_status": p["scope_status"], "synthetic_demo_allowed": bool(p.get("synthetic_demo_allowed")),
                              "scenario_code": p.get("scenario"), "test_tags": p.get("test_tags", []),
                              "data_quality_flags": p.get("data_quality_flags", [])})
        for e in p["employers"]:
            t["employers"].append({"profile_id": pid, **{c: e.get(c) for c in EMPLOYER_COLS if c != "profile_id"}})
        for e in p["employments"]:
            sy, sm = split_date(e.get("start"), e["start_precision"])
            ey, em = split_date(e.get("end"), e["end_precision"])
            row = {c: e.get(c) for c in EMPLOYMENT_COLS}
            row.update({"profile_id": pid, "start_year": sy, "start_month": sm, "end_year": ey, "end_month": em,
                        "mapping_confidence": float(e["mapping_confidence"]),
                        "extraction_status": "synthetic_curated" if p["dataset_class"] == "synthetic_test_fixture" else "extracted_unverified",
                        "data_quality_flags": e.get("data_quality_flags", [])})
            t["employments"].append(row)
        for d in p.get("education", []):
            sy, sm = split_date(d.get("start"), d["start_precision"])
            ey, em = split_date(d.get("end"), d["end_precision"])
            t["education"].append({"education_id": d["education_id"], "profile_id": pid, "qualification_level": d["qualification_level"],
                                   "field_of_study": d.get("field_of_study"), "study_mode": d["study_mode"],
                                   "completion_status": d["completion_status"], "start_year": sy, "start_month": sm,
                                   "start_precision": d["start_precision"], "end_year": ey, "end_month": em, "end_precision": d["end_precision"]})
        for b in p.get("career_breaks", []):
            sy, sm = split_date(b.get("start"), b["start_precision"])
            ey, em = split_date(b.get("end"), b["end_precision"])
            t["career_breaks"].append({"break_id": b["break_id"], "profile_id": pid, "break_reason": b["break_reason"],
                                       "note_redacted": b.get("note_redacted"), "start_year": sy, "start_month": sm,
                                       "start_precision": b["start_precision"], "end_year": ey, "end_month": em,
                                       "end_precision": b["end_precision"]})
        for x in p["evidence"]:
            t["experience_evidence"].append({"evidence_id": x["evidence_id"], "profile_id": pid, "employment_id": x.get("employment_id"),
                                             "evidence_type": x["evidence_type"], "responsibility_area": x.get("responsibility_area"),
                                             "evidence_text_redacted": x["text"], "provenance": x["provenance"],
                                             "evidence_status": x["evidence_status"], "confidence": x.get("confidence")})
        for s in p.get("skills", []):
            sid = "-".join(filter(None, [pid, s["skill_id"], s["evidence_source"], s.get("employment_id")]))
            t["profile_skills"].append({"profile_skill_id": sid, "profile_id": pid, "skill_id": s["skill_id"],
                                        "skill_text_raw": s.get("skill_text_raw"), "employment_id": s.get("employment_id"),
                                        "evidence_id": s.get("evidence_id"), "evidence_source": s["evidence_source"],
                                        "confidence": s.get("confidence"), "verified": bool(s.get("verified"))})
    return t


def fixture_pdf_hashes(profiles, root=ROOT):
    """The approved (fixture id, PDF SHA-256) pairs, derived from the rendered PDF archive. The archive
    must hold exactly one <profile_id>_synthetic_resume.pdf per synthetic profile and nothing else, and
    no two fixtures may share a PDF. These pairs are trace_ingest's fixture allowlist (v2.4.0)."""
    expected = {p["profile_id"]: f"{p['profile_id']}_synthetic_resume.pdf" for p in profiles}
    with zipfile.ZipFile(root / SYNTHETIC_PDF_ZIP) as z:
        names = set(z.namelist())
        if names != set(expected.values()):
            raise SystemExit(f"{SYNTHETIC_PDF_ZIP} does not match the synthetic profiles: "
                             f"missing {sorted(set(expected.values()) - names)}, unexpected {sorted(names - set(expected.values()))}")
        rows = [{"fixture_profile_id": pid, "pdf_sha256": hashlib.sha256(z.read(name)).hexdigest()}
                for pid, name in sorted(expected.items())]
    if len({r["pdf_sha256"] for r in rows}) != len(rows):
        raise SystemExit(f"{SYNTHETIC_PDF_ZIP}: two fixtures share one PDF")
    return rows


def build_synthetic_sql(profiles, lk, pdf_hashes=()):
    t = flatten(profiles)
    pids = [p["profile_id"] for p in t["profiles"]]
    keep = lambda rows, key: [r[key] for r in rows]  # noqa: E731
    out = [GENERATED_BANNER.format(src=SYNTHETIC_JSONL),
           "-- Trace Data Foundation v2 · synthetic test fixtures.\n"
           "-- FOR LOCAL, PREVIEW-BRANCH AND DEDICATED TEST DATABASES ONLY. Never run against production.\n"
           "-- Fully repeatable: upserts on stable ids, and synthetic rows that are no longer in the\n"
           "-- source file are deleted, so the database matches the file after every run.\n\n",
           "begin;\n\n",
           "do $$\nbegin\n"
           "  if exists (select 1 from trace_ref.profiles where dataset_class = 'consented_real_reference') then\n"
           "    raise exception 'Refusing to load synthetic fixtures: this database holds consented real reference profiles. "
           "Load synthetic fixtures only into local, preview-branch or dedicated test databases.';\n"
           "  end if;\nend\n$$;\n\n"]
    out.append(upsert("trace_ref.data_sources", SOURCE_COLS,
                      [source_row(s) for s in lk["sources"] if s["seed_target"] == "synthetic_seed"], ["source_id"]))
    out.append("-- Remove synthetic rows that are no longer in the source file.\n")
    out.append(f"delete from trace_ref.profiles where dataset_class = 'synthetic_test_fixture' and profile_id <> all ({lit(pids)});\n")
    for table, rows, key in (("trace_ref.profile_skills", t["profile_skills"], "profile_skill_id"),
                             ("trace_ref.experience_evidence", t["experience_evidence"], "evidence_id"),
                             ("trace_ref.career_breaks", t["career_breaks"], "break_id"),
                             ("trace_ref.education", t["education"], "education_id"),
                             ("trace_ref.employments", t["employments"], "employment_id")):
        out.append(f"delete from {table} where profile_id = any ({lit(pids)}) and {key} <> all ({lit(keep(rows, key))});\n")
    emp_keys = [f"{r['profile_id']}|{r['employer_id']}" for r in t["employers"]]
    out.append(f"delete from trace_ref.employers where profile_id = any ({lit(pids)}) "
               f"and (profile_id || '|' || employer_id) <> all ({lit(emp_keys)});\n\n")
    out.append(upsert("trace_ref.profiles", PROFILE_COLS, t["profiles"], ["profile_id"]))
    out.append(upsert("trace_ref.employers", EMPLOYER_COLS, t["employers"], ["profile_id", "employer_id"]))
    out.append(upsert("trace_ref.employments", EMPLOYMENT_COLS, t["employments"], ["employment_id"]))
    out.append(upsert("trace_ref.education", EDUCATION_COLS, t["education"], ["education_id"]))
    out.append(upsert("trace_ref.career_breaks", BREAK_COLS, t["career_breaks"], ["break_id"]))
    out.append(upsert("trace_ref.experience_evidence", EVIDENCE_COLS, t["experience_evidence"], ["evidence_id"]))
    out.append(upsert("trace_ref.profile_skills", SKILL_COLS, t["profile_skills"], ["profile_skill_id"]))
    if pdf_hashes:
        out.append(f"-- Approved synthetic fixture resumes: the trace_ingest allowlist (v2.4.0). Each fixture id is\n"
                   f"-- paired with the SHA-256 of its PDF in {SYNTHETIC_PDF_ZIP}. Rows of removed fixtures go\n"
                   f"-- with their trace_ref.profiles row (ON DELETE CASCADE).\n")
        out.append(upsert("trace_ingest.approved_fixture_resumes", ["fixture_profile_id", "pdf_sha256"], list(pdf_hashes),
                          ["fixture_profile_id"]))
    out.append("commit;\n")
    return "".join(out)


def to_csv(rows, cols):
    buf = io.StringIO()
    w = csv.writer(buf, lineterminator="\n")
    w.writerow(cols)
    for r in rows:
        vals = []
        for c in cols:
            v = r.get(c)
            if isinstance(v, list):
                v = "|".join(v)
            elif isinstance(v, bool):
                v = "true" if v else "false"
            elif v is None:
                v = ""
            vals.append(v)
        w.writerow(vals)
    return buf.getvalue()


def fmt_period(start, sp, end, ep):
    s = start if sp in ("month", "year") else "date not stated"
    if ep == "ongoing":
        e = "Present (synthetic)"
    elif ep in ("month", "year"):
        e = end
    else:
        e = "date not stated"
    return f"{s} to {e}"


def build_cards(profiles, roles):
    lines = ["# Synthetic Indian PM-transition resume fixtures", "",
             "> GENERATED by scripts/build_seeds.py from data/synthetic/synthetic_profiles.jsonl. Do not edit by hand.",
             "> Every profile below is synthetic and generated solely for system testing. Fictional employers, dates, titles and",
             "> accomplishments are not real people or market evidence. Do not use these records to calculate market frequencies,",
             "> success probabilities or empirical timelines.", ""]
    for p in profiles:
        lines += [f"## {p['profile_id']} - {p['scenario'].replace('_', ' ').capitalize()}", "",
                  "**SYNTHETIC TEST PROFILE - NOT A REAL PERSON**", "", p["profile_summary"], "",
                  f"**Resume as of:** {p.get('resume_as_of') or 'unknown'}", "",
                  f"**Test tags:** {', '.join(p.get('test_tags', []))}", ""]
        edu = "; ".join(f"{d['qualification_level']}{' - ' + d['field_of_study'] if d.get('field_of_study') else ''}"
                        f"{' (' + fmt_period(d.get('start'), d['start_precision'], d.get('end'), d['end_precision']) + ')' if d['start_precision'] != 'unknown' else ''}"
                        for d in p.get("education", []))
        lines += [f"**Education:** {edu or 'not stated'}", "",
                  f"**Skills:** {', '.join(s.get('skill_text_raw') or s['skill_id'] for s in p.get('skills', []))}", "",
                  "**Experience**", ""]
        employers = {e["employer_id"]: e for e in p["employers"]}
        ev = {}
        for x in p["evidence"]:
            ev.setdefault(x["employment_id"], []).append(x["text"])
        for e in sorted(p["employments"], key=lambda e: e["sequence_index"]):
            emp = employers.get(e["employer_id"]) or {}
            lines.append(f"### {e['title_raw_redacted']} | {e['employer_id'] or 'employer not stated'} | "
                         f"{fmt_period(e.get('start'), e['start_precision'], e.get('end'), e['end_precision'])}")
            meta = [f"Industry: {emp.get('industry_raw') or 'not stated'}", f"Type: {e['employment_type']}",
                    f"Mapped role: {e['role_id']} ({roles[e['role_id']]['role_family']}, {e['mapping_status']})"]
            if not e["primary_career_sequence"]:
                meta.append("Parallel activity (not in linear sequence)")
            lines.append(" · ".join(meta))
            if e.get("classification_note"):
                lines.append(f"Note: {e['classification_note']}")
            for text in ev.get(e["employment_id"], []):
                lines.append(f"- {text}")
            lines.append("")
        for b in p.get("career_breaks", []):
            lines += [f"### Career break ({b['break_reason']}) | {fmt_period(b.get('start'), b['start_precision'], b.get('end'), b['end_precision'])}",
                      f"- {b.get('note_redacted') or ''}".rstrip(), ""]
        lines += ["---", ""]
    return "\n".join(lines).rstrip() + "\n"


def build_coverage(profiles):
    rows = []
    for p in profiles:
        seq = " -> ".join(e["title_raw_redacted"] for e in sorted(p["employments"], key=lambda e: e["sequence_index"]))
        rows.append({"profile_id": p["profile_id"], "scenario": p["scenario"], "career_sequence": seq,
                     "test_tags": p.get("test_tags", []), "dataset_class": p["dataset_class"],
                     "analytics_eligible": False, "synthetic_demo_allowed": bool(p.get("synthetic_demo_allowed"))})
    return to_csv(rows, ["profile_id", "scenario", "career_sequence", "test_tags", "dataset_class",
                         "analytics_eligible", "synthetic_demo_allowed"])


# --------------------------------------------------------------------------- manifest
def sha256(path):
    return hashlib.sha256(path.read_bytes()).hexdigest()


def shareable_files(root=ROOT):
    out = []
    for p in sorted(root.rglob("*")):
        rel = p.relative_to(root)
        if not p.is_file() or rel.parts[0] in MANIFEST_EXCLUDE_DIRS or p.name in MANIFEST_EXCLUDE_NAMES:
            continue
        if any(part in MANIFEST_EXCLUDE_DIRS for part in rel.parts):
            continue
        if rel.parts[:2] in MANIFEST_EXCLUDE_PATHS:
            continue
        out.append(rel)
    return out


def build_manifest(profiles, generated, root=ROOT):
    """`generated` maps relative path -> content that is about to be written, so the manifest
    hashes the post-build state even in --check mode."""
    files = []
    for rel in shareable_files(root):
        key = rel.as_posix()
        if key in generated:
            data = generated[key].encode("utf-8")
            files.append({"path": key, "bytes": len(data), "sha256": hashlib.sha256(data).hexdigest()})
        else:
            p = root / rel
            files.append({"path": key, "bytes": p.stat().st_size, "sha256": sha256(p)})
    for key in sorted(generated):
        if key != "manifest.json" and not (root / key).exists():
            data = generated[key].encode("utf-8")
            files.append({"path": key, "bytes": len(data), "sha256": hashlib.sha256(data).hexdigest()})
    files.sort(key=lambda f: f["path"])
    manifest = {
        "project": "Trace Data Foundation",
        "version": "2.2.0",
        "geography": "India",
        "shared_database_contents": {
            "synthetic_test_profiles": len(profiles),
            "synthetic_employment_records": sum(len(p["employments"]) for p in profiles),
            "synthetic_evidence_records": sum(len(p["evidence"]) for p in profiles),
            "uploaded_resume_fixtures": 0,
            "consented_real_reference_profiles": 0,
            "profiles_eligible_for_empirical_analytics": 0,
        },
        # Static by design: the manifest never depends on, lists or counts restricted local files,
        # so it is identical whether or not local_only/ is present.
        "restricted_material": {
            "included": False,
            "note": "Restricted local-only material is excluded from this package and from every shared database.",
        },
        "files": files,
    }
    return json.dumps(manifest, indent=2, ensure_ascii=False) + "\n"


# --------------------------------------------------------------------------- main
def generate(root=ROOT):
    lk = load_lookups(root)
    profiles = tm.read_jsonl(root / SYNTHETIC_JSONL)
    roles = {r["role_id"]: r for r in lk["roles"]}
    t = flatten(profiles)
    pdf_hashes = fixture_pdf_hashes(profiles, root)
    gen = {
        LOOKUP_MIGRATION: build_lookup_sql(lk),
        SYNTHETIC_SEED: build_synthetic_sql(profiles, lk, pdf_hashes),
        SYNTHETIC_PDF_HASHES: to_csv(pdf_hashes, ["fixture_profile_id", "pdf_sha256"]),
        "data/synthetic/synthetic_resume_cards.md": build_cards(profiles, roles),
        "data/synthetic/synthetic_scenario_coverage.csv": build_coverage(profiles),
        "data/synthetic/csv/profiles.csv": to_csv(t["profiles"], PROFILE_COLS),
        "data/synthetic/csv/employers.csv": to_csv(t["employers"], EMPLOYER_COLS),
        "data/synthetic/csv/employments.csv": to_csv(t["employments"], EMPLOYMENT_COLS),
        "data/synthetic/csv/education.csv": to_csv(t["education"], EDUCATION_COLS),
        "data/synthetic/csv/career_breaks.csv": to_csv(t["career_breaks"], BREAK_COLS),
        "data/synthetic/csv/experience_evidence.csv": to_csv(t["experience_evidence"], EVIDENCE_COLS),
        "data/synthetic/csv/profile_skills.csv": to_csv(t["profile_skills"], SKILL_COLS),
    }
    gen["manifest.json"] = build_manifest(profiles, gen, root)
    return gen


def stale_artefacts(root=ROOT):
    stale = []
    for rel, content in generate(root).items():
        p = root / rel
        if not p.exists() or p.read_text(encoding="utf-8") != content:
            stale.append(rel)
    return stale


def main(argv):
    if "--check" in argv:
        stale = stale_artefacts()
        if stale:
            print("Out-of-date generated artefacts (run python3 scripts/build_seeds.py):")
            for s in stale:
                print(f"  {s}")
            return 1
        print("All generated artefacts are up to date.")
        return 0
    gen = generate()
    for rel, content in gen.items():
        if rel == "manifest.json":
            continue
        p = ROOT / rel
        p.parent.mkdir(parents=True, exist_ok=True)
        p.write_text(content, encoding="utf-8")
    # Rebuild the manifest after writing so it hashes the files on disk.
    (ROOT / "manifest.json").write_text(generate()["manifest.json"], encoding="utf-8")
    print(f"Wrote {len(gen)} generated artefacts.")
    return 0


if __name__ == "__main__":
    sys.exit(main(sys.argv[1:]))
